def uri(body):
    svg = "<svg xmlns='http://www.w3.org/2000/svg' viewBox='0 0 16 16'>%s</svg>" % body
    return "data:image/svg+xml," + quote(svg, safe="/:=' ,().-_~")


def block():
    out = [BEGIN]
    for name in sorted(ICONS):
        out.append('.bi-%s{--i:url("%s")}' % (name, uri(ICONS[name])))
    out.append(END)
    return "\n".join(out)


def sheet():
    cells = "".join(
        "<div style='display:inline-block;width:110px;text-align:center;margin:6px;font:11px sans-serif'>"
        "<i class='bi bi-%s' style='font-size:40px'></i><br>%s</div>" % (n, n) for n in sorted(ICONS))
    return "<!doctype html><link rel=stylesheet href=/ui.css><body style='background:var(--body-bg);color:var(--body-color)'>%s" % cells


if __name__ == "__main__":
    if "--sheet" in sys.argv:
        print(sheet())
    else:
        css = CSS.read_text()
        pat = re.compile(re.escape(BEGIN) + r".*?" + re.escape(END), re.S)
        if not pat.search(css):
            sys.exit("markers not found in %s" % CSS)
        CSS.write_text(pat.sub(lambda m: block(), css))
        print("wrote %d icons into %s" % (len(ICONS), CSS))
