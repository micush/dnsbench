S = "fill='none' stroke='black' stroke-width='1.4' stroke-linecap='round' stroke-linejoin='round'"
F = "fill='black'"


def stroke(*d):
    return "<g %s>%s</g>" % (S, "".join("<path d='%s'/>" % p for p in d))


def fill(*d, rule=None):
    extra = " fill-rule='evenodd'" if rule else ""
    return "".join("<path %s%s d='%s'/>" % (F, extra, p) for p in d)


def cutout(shape, *marks, sw=1.5):
    """A filled shape with strokes punched out of it (transparent in the mask)."""
    cut = "".join("<path d='%s'/>" % m for m in marks)
    return (
        "<mask id='m'><rect width='16' height='16' fill='white'/>"
        "<g fill='none' stroke='black' stroke-width='%s' stroke-linecap='round' stroke-linejoin='round'>%s</g></mask>"
        "<g mask='url(#m)' %s>%s</g>" % (sw, cut, F, shape)
    )


